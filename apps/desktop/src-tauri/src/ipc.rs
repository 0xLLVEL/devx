//! Typed IPC surface: command registry, event registry and binding export.
//!
//! `src/bindings.ts` is generated from this registry and **committed** to the
//! repository, so the frontend can be type-checked without first building the
//! Rust side. `tests/ipc.rs` asserts the committed file matches the registry;
//! run `DEVX_UPDATE_BINDINGS=1 cargo test -p devx-desktop` to refresh it.

use std::path::Path;

use tauri_specta::{collect_commands, collect_events};

use crate::{commands, events};

/// Path of the generated TypeScript client, relative to `src-tauri`.
pub const BINDINGS_PATH: &str = "../src/bindings.ts";

/// Builds the `tauri-specta` builder holding every command and event.
///

/// Writes the TypeScript client for `builder` to `path`.
pub fn export_bindings_to(
    builder: &tauri_specta::Builder<tauri::Wry>,
    path: impl AsRef<Path>,
) -> Result<(), String> {
    use specta_typescript::Typescript;

    let config = Typescript::default().header(
        "// Generated by tauri-specta from apps/desktop/src-tauri/src/ipc.rs.\n// Do not edit by hand: run `cargo test -p devx-desktop` to verify.\n",
    );

    builder
        .export(config, path)
        .map_err(|err| format!("failed to export TypeScript bindings: {err}"))
}

/// Refreshes the committed `src/bindings.ts`.
///
/// Debug builds only: a packaged release must never write into a source tree.
#[cfg(debug_assertions)]
pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) -> Result<(), String> {
    export_bindings_to(builder, BINDINGS_PATH)
}
